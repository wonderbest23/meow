export function bigIndustryFor(input: { ksic?: string | null; text?: string | null }): BigIndustry | null {
  if (input.ksic) {
    const byCode = BIG_INDUSTRIES.find(item => item.ksic.includes(input.ksic!));
    if (byCode) return byCode;
  }
  const text = input.text?.trim();
  if (!text) return null;
  return BIG_INDUSTRIES.find(item => item.words.test(text)) ?? null;
}

