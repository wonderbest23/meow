/** 공통 사업 정보(JSON)에서 글 쓰는 데 필요 없는 추적용 값을 뺀다 — 메시지 id·버전 번호는 토큰만 쓰고 판단에 쓰이지 않는다 */
export function compactCoachContext(coachContext: string): string {
  try {
    const drop = new Set(["messageId", "version", "revision", "sourceRevision"]);
    return JSON.stringify(JSON.parse(coachContext, (key, value) => (drop.has(key) ? undefined : value)), null, 1);
  } catch {
    return coachContext;
  }
}
