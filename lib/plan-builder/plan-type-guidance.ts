/** 프롬프트에 넣을 지침 블록. 정의가 없는 유형이면 빈 문자열. */
export function planTypeGuidanceBlock(planType?: string): string {
  const g = planType ? PLAN_TYPE_GUIDANCE[planType] : undefined;
  if (!g) return "";
  return [
    `\n[이 문서의 성격 — ${planType}]`,
    `읽는 사람: ${g.reader}`,
    `그 사람이 내리려는 결정: ${g.decision}`,
    `문체: ${g.tone}`,
    "반드시 다룰 것:",
    ...g.emphasize.map((line) => `- ${line}`),
    "쓰지 말 것:",
    ...g.avoid.map((line) => `- ${line}`),
  ].join("\n");
}
