/** KSIC 코드에 맞는 가이드. 앞자리가 가장 길게 맞는 것을 고른다 */
export function playbookForKsic(code: string | null | undefined): IndustryPlaybook | null {
  if (!code) return null;
  let best: { playbook: IndustryPlaybook; length: number } | null = null;
  for (const playbook of INDUSTRY_PLAYBOOKS) for (const prefix of playbook.ksic) {
    if (code.startsWith(prefix) && (!best || prefix.length > best.length)) best = { playbook, length: prefix.length };
  }
  return best?.playbook ?? null;
}

/*
 * 업종 코드를 아직 고르지 않은 사업(상담으로 시작한 사업은 대부분 비어 있다)도 사업 설명으로 가이드를 찾는다.
 * 2026-10-11 빵집 시험: 업종 코드가 없어 위생교육·건강진단·건축물 용도가 계획서에서 빠졌다.
 * 위에서부터 처음 맞는 것을 쓴다 — 매장 업종을 온라인 판매보다 먼저 본다(빵을 온라인으로도 파는 빵집은 빵집).
 */
const PLAYBOOK_WORDS: Array<[string, RegExp]> = [
  ["bakery", /빵집|베이커리|제과점|제과\s*(가게|매장)|빵\s*(가게|매장)/],
  ["cafe", /(?<!네이버\s?|다음\s?)카페|커피\s*(전문점|가게|매장|숍|샵)/],
  ["side-dish", /반찬\s*(가게|매장|배달)?|도시락\s*(가게|전문점|배달)/],
  ["snack", /분식|김밥\s*(집|가게)|떡볶이/],
  ["restaurant", /음식점|식당|한식집|중식당|일식집|레스토랑|고깃집/],
  ["beauty", /미용실|헤어\s*(숍|샵)|네일\s*(숍|샵|아트)?|피부\s*관리|속눈썹/],
  ["academy", /학원|교습소|공부방|과외/],
  ["gym", /헬스장|체력\s*단련장|피트니스\s*(센터|클럽)/],
  ["lodging", /민박|게스트\s*하우스|공유\s*숙박|에어비앤비/],
  ["rental-room", /연습실|스터디\s*룸|파티\s*룸|시간\s*대여/],
  ["brokerage", /연결해\s*주|이어\s*주는|중개|매칭|소개팅|소개해\s*주/],
  ["online-store", /스마트스토어|온라인\s*(쇼핑몰|판매|스토어)|쇼핑몰|오픈마켓/],
];

export function playbookForText(text: string | null | undefined): IndustryPlaybook | null {
  if (!text?.trim()) return null;
  const id = PLAYBOOK_WORDS.find(([, words]) => words.test(text))?.[0];
  return INDUSTRY_PLAYBOOKS.find(playbook => playbook.id === id) ?? null;
}

/** 사업 관리 단계 자료로 쓰는 글 — 그대로 복사해 체크리스트로 쓸 수 있게 */
export function playbookChecklist(playbook: IndustryPlaybook): string {
  return [
    `${playbook.name} 시작 준비 (오늘창업 정리 ${PLAYBOOK_REVIEWED_AT} · 관할 기관 확인 필요)`,
    "",
    "■ 준비할 것",
    ...playbook.needs.map(item => `- [ ] ${item}`),
    "",
    "■ 순서",
    ...playbook.steps.map((step, index) => `${index + 1}. ${step.title} — ${step.where}\n   ${step.detail}\n   확인한 날짜·담당자:`),
    "",
    "■ 자주 놓치는 것",
    ...playbook.pitfalls.map(item => `- ${item}`),
  ].join("\n");
}

